    def _charger_especes_depuis_bdd(self, groupe):
        """
        Charge les espèces depuis :
        - bdfauneflore.w_ref_faune si groupe = faune
        - bdfauneflore.w_ref_flore si groupe = flore

        Champs utilisés :
        - cd_nom
        - nom_complet
        """

        try:
            if self.pg_service_path and os.path.exists(self.pg_service_path):
                os.environ["PGSERVICEFILE"] = self.pg_service_path

            groupe = groupe.strip().lower()

            if groupe == "faune":
                table = "bdfauneflore.w_ref_faune"
            elif groupe == "flore":
                table = "bdfauneflore.w_ref_flore"
            else:
                return

            conn = psycopg2.connect(service="bd CEN (admin)")
            cur = conn.cursor()

            sql = f"""
                SELECT
                    cd_nom,
                    nom_complet
                FROM {table}
                WHERE nom_complet IS NOT NULL
                And cd_nom = cd_ref
                ORDER BY nom_complet ASC;
            """

            cur.execute(sql)

            rows = cur.fetchall()

            cur.close()
            conn.close()

            self._all_especes = []

            for cd_nom, nom_complet in rows:
                self._all_especes.append({
                    "cd_nom": cd_nom,
                    "nom_complet": nom_complet or "",
                    "groupe": groupe,
                })

            print(f"{len(self._all_especes)} espèce(s) chargée(s) pour le groupe {groupe}")

        except Exception as e:
            QMessageBox.critical(
                self,
                "Erreur BDD",
                f"Impossible de charger les espèces du groupe '{groupe}' :\n{e}"
            )


