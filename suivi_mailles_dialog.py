    def charger_geopackage_terrain(self):
        """
        Charge la couche mailles_suivi depuis le GeoPackage terrain.
        """

        chemin_gpkg = self.le_fichier_gpkg_terrain.text().strip()
        nom_couche = self.le_couche_mailles_terrain.text().strip()

        if not chemin_gpkg:
            QMessageBox.warning(
                self,
                "GeoPackage manquant",
                "Veuillez sélectionner un GeoPackage terrain."
            )
            return

        if not os.path.exists(chemin_gpkg):
            QMessageBox.warning(
                self,
                "Fichier introuvable",
                f"Le fichier GeoPackage n'existe pas :\n\n{chemin_gpkg}"
            )
            return

        if not chemin_gpkg.lower().endswith(".gpkg"):
            QMessageBox.warning(
                self,
                "Fichier invalide",
                "Le fichier sélectionné n'est pas un GeoPackage .gpkg."
            )
            return

        if not nom_couche:
            nom_couche = "mailles_suivi"
            self.le_couche_mailles_terrain.setText(nom_couche)

        uri = f"{chemin_gpkg}|layername={nom_couche}"

        layer = QgsVectorLayer(uri, nom_couche, "ogr")

        if not layer.isValid():
            QMessageBox.critical(
                self,
                "Erreur de chargement",
                (
                    "Impossible de charger la couche du GeoPackage.\n\n"
                    f"Fichier : {chemin_gpkg}\n"
                    f"Couche : {nom_couche}"
                )
            )
            return

        try:
            self._verifier_champs_couche_suivi_terrain(layer)
        except Exception as e:
            QMessageBox.critical(
                self,
                "Couche invalide",
                str(e)
            )
            return

        # Appliquer le style automatique :
        # vert = présence, rouge = absence, transparent = non renseigné
        self._appliquer_style_presence_absence(layer)

        # Ajouter la couche mailles_suivi au projet QGIS
        QgsProject.instance().addMapLayer(layer)

        # Lire metadata_suivi (remplit temporairement self.metadata_suivi_terrain)
        self._charger_metadata_suivi_terrain(chemin_gpkg)
        metadata = dict(self.metadata_suivi_terrain)

        uuid_suivi = metadata.get("uuid_suivi") or str(uuid.uuid4())

        if uuid_suivi in self.suivis_terrain:
            QMessageBox.warning(
                self,
                "Suivi déjà chargé",
                "Ce suivi est déjà chargé dans la session terrain."
            )
            QgsProject.instance().removeMapLayer(layer.id())
            return

        # Distinguer visuellement ce suivi dans le panneau QGIS, sans toucher
        # au nom de la table (qui doit rester "mailles_suivi" pour que le
        # transfert vers PostgreSQL continue de fonctionner).
        codesitep = metadata.get("codesitep")
        taille_maille = metadata.get("taille_maille")
        nom_espece = metadata.get("nom_complet")

        parties_nom = []
        if codesitep:
            parties_nom.append(str(codesitep))
        if taille_maille:
            parties_nom.append(f"{taille_maille}m")
        if nom_espece:
            parties_nom.append(str(nom_espece))

        nom_affiche = " — ".join(parties_nom) if parties_nom else nom_couche
        layer.setName(nom_affiche)

        couleur = self._palette_couleurs_suivis_terrain[
            len(self.suivis_terrain) % len(self._palette_couleurs_suivis_terrain)
        ]

        # Charger aussi la table metadata_suivi dans QGIS
        layer_metadata = self._charger_table_metadata_suivi_qgis(chemin_gpkg)

        self.suivis_terrain[uuid_suivi] = {
            "layer": layer,
            "layer_metadata": layer_metadata,
            "metadata": metadata,
            "couleur": couleur,
            "chemin_gpkg": chemin_gpkg,
            "nom_affiche": nom_affiche,
        }

        self.cb_suivi_actif_terrain.blockSignals(True)
        self.cb_suivi_actif_terrain.addItem(nom_affiche, uuid_suivi)
        self.cb_suivi_actif_terrain.setCurrentIndex(
            self.cb_suivi_actif_terrain.count() - 1
        )
        self.cb_suivi_actif_terrain.blockSignals(False)

        self.btn_decharger_suivi_terrain.setEnabled(True)

        # Bascule effectivement l'édition sur ce suivi qui vient d'être ajouté
        self._basculer_suivi_terrain()

        self._log_terrain(
            "GeoPackage chargé avec succès.\n"
            f"Suivi : {nom_affiche}\n"
            f"Nombre de mailles : {layer.featureCount()}"
        )

        QMessageBox.information(
            self,
            "GeoPackage chargé",
            (
                "Le GeoPackage terrain a été chargé avec succès.\n\n"
                f"Suivi : {nom_affiche}\n"
                f"Nombre de mailles : {layer.featureCount()}\n"
                "Table metadata_suivi chargée si elle existe."
            )
        )



    def _verifier_champs_couche_suivi_terrain(self, layer):
        """
        Vérifie que la couche mailles_suivi contient les champs attendus.
        """

        champs_obligatoires = [
            "uuid_resultat",
            "uuid_suivi",
            "id_maille",
            "code_maille",
            "taille_maille",
            "date_obs",
            "presence_absence",
        ]

        noms_champs = [field.name() for field in layer.fields()]

        champs_manquants = []

        for champ in champs_obligatoires:
            if champ not in noms_champs:
                champs_manquants.append(champ)

        if champs_manquants:
            raise Exception(
                "La couche chargée n'est pas une couche de suivi valide.\n\n"
                "Champs manquants :\n"
                + "\n".join(f"- {champ}" for champ in champs_manquants)
            )

    def _charger_metadata_suivi_terrain(self, chemin_gpkg):
        """
        Lit la table metadata_suivi du GeoPackage.
        """

        self.metadata_suivi_terrain = {}

        try:
            sqlite_conn = sqlite3.connect(chemin_gpkg)
            sqlite_cur = sqlite_conn.cursor()

            sqlite_cur.execute("""
                SELECT
                    uuid_suivi,
                    id_perm,
                    codesitep,
                    nom_site,
                    groupe_suivi,
                    cd_nom,
                    nom_complet,
                    taille_maille,
                    id_obs,
                    observateur,
                    nom_fichier_gpkg,
                    date_export
                FROM metadata_suivi
                LIMIT 1;
            """)

            row = sqlite_cur.fetchone()

            sqlite_cur.close()
            sqlite_conn.close()

            if not row:
                self._log_terrain("Aucune métadonnée trouvée dans metadata_suivi.")
                return

            self.metadata_suivi_terrain = {
                "uuid_suivi": row[0],
                "id_perm": row[1],
                "codesitep": row[2],
                "nom_site": row[3],
                "groupe_suivi": row[4],
                "cd_nom": row[5],
                "nom_complet": row[6],
                "taille_maille": row[7],
                "id_obs": row[8],
                "observateur": row[9],
                "nom_fichier_gpkg": row[10],
                "date_export": row[11],
            }

            self._log_terrain(
                "Métadonnées du suivi :\n"
                f"- UUID suivi : {row[0]}\n"
                f"- ID permanent : {row[1]}\n"
                f"- Site : {row[3]} ({row[2]})\n"
                f"- Groupe : {row[4]}\n"
                f"- Espèce : {row[6]} ({row[5]})\n"
                f"- Observateur : {row[9]}\n"
                f"- Taille maille : {row[7]} m"
            )

        except Exception as e:
            self._log_terrain(
                f"Attention : impossible de lire la table metadata_suivi : {e}"
            )

