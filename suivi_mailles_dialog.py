    def creer_suivi(self):
        """
        Crée un suivi espèce :
        - insertion dans suivi_cen.suivi_espece
        - récupération des mailles du site
        - création du GeoPackage terrain choisi par l'utilisateur
        - création de la table metadata_suivi
        - mise à jour du statut en 'exporte'
        """

        progress = QProgressDialog(
        "Création du suivi en cours...\nVeuillez patienter.",
        None,
        0,
        0,
        self
        )
        progress.setWindowTitle("Traitement en cours")
        progress.setWindowModality(QT_WINDOW_MODAL)
        progress.setCancelButton(None)
        progress.setMinimumDuration(0)
        progress.show()
        QApplication.setOverrideCursor(QT_WAIT_CURSOR)
        QApplication.processEvents()
        try:
            # ------------------------------------------------------------
            # 1. Vérifications des sélections obligatoires
            # ------------------------------------------------------------

            if not self.selected_codesitep:
                QMessageBox.warning(
                    self,
                    "Site non sélectionné",
                    "Veuillez sélectionner un site dans la liste proposée."
                )
                return

            if not self.selected_cd_nom:
                QMessageBox.warning(
                    self,
                    "Espèce non sélectionnée",
                    "Veuillez sélectionner une espèce dans la liste proposée."
                )
                return

            if not self.selected_observateur:
                QMessageBox.warning(
                    self,
                    "Observateur non sélectionné",
                    "Veuillez sélectionner un observateur dans la liste proposée."
                )
                return

            if getattr(self, "selected_id_obs", None) is None:
                QMessageBox.warning(
                    self,
                    "Identifiant observateur manquant",
                    "L'observateur est sélectionné, mais son identifiant id n'a pas été récupéré."
                )
                return

            try:
                taille_maille = self._get_taille_maille()
            except Exception as e:
                QMessageBox.warning(
                    self,
                    "Taille de maille manquante",
                    str(e)
                )
                return

            groupe_suivi = str(self.selected_groupe_espece).strip().lower()

    #####################################

            if groupe_suivi not in ("faune", "flore"):
                QMessageBox.warning(
                    self,
                    "Groupe invalide",
                    "Le groupe du suivi doit être 'faune' ou 'flore'."
                )
                return

            # ------------------------------------------------------------
            # 2. Récupération du fichier GeoPackage choisi par l'utilisateur
            # ------------------------------------------------------------

            chemin_gpkg = self.le_fichier_gpkg_export.text().strip()

            if not chemin_gpkg:
                QMessageBox.warning(
                    self,
                    "Fichier GeoPackage manquant",
                    "Veuillez choisir le fichier GeoPackage à créer."
                )
                return

            if not chemin_gpkg.lower().endswith(".gpkg"):
                chemin_gpkg += ".gpkg"
                self.le_fichier_gpkg_export.setText(chemin_gpkg)

            chemin_gpkg = os.path.abspath(chemin_gpkg)

            dossier_export = os.path.dirname(chemin_gpkg)

            if not dossier_export or not os.path.isdir(dossier_export):
                QMessageBox.warning(
                    self,
                    "Dossier invalide",
                    "Le dossier du fichier GeoPackage n'existe pas."
                )
                return


            nom_fichier_gpkg = os.path.basename(chemin_gpkg)
            gpkg_cree_par_ce_traitement = False

            # Si le fichier existe déjà, demander confirmation
            if os.path.exists(chemin_gpkg):
                reponse = QMessageBox.question(
                    self,
                    "Fichier existant",
                    f"Le fichier existe déjà :\n\n{chemin_gpkg}\n\n"
                    "Voulez-vous le remplacer ?",
                    QMSG_YES | QMSG_NO,
                    QMSG_NO
                )

                if reponse != QMSG_YES:
                    return

            # ------------------------------------------------------------
            # 3. Horodatage (l'id_perm est généré plus loin, une fois le
            #    code_site_mere connu : c'est lui qui identifie le suivi,
            #    pas le codesitep du sous-site sélectionné dans l'UI).
            # ------------------------------------------------------------

            maintenant = datetime.now()


            # ------------------------------------------------------------
            # 4. Connexion PostgreSQL
            # ------------------------------------------------------------

            pg_conn = None
            pg_cur = None

            try:
                if self.pg_service_path and os.path.exists(self.pg_service_path):
                    os.environ["PGSERVICEFILE"] = self.pg_service_path

                pg_conn = psycopg2.connect(service="bd CEN (admin)")
                pg_cur = pg_conn.cursor()

                # --------------------------------------------------------
                # 4a. Résolution du site mère (fait AVANT la recherche de
                #     suivi existant, car l'identifiant de regroupement du
                #     suivi est le code_site_mere, pas le codesitep choisi
                #     par l'utilisateur).
                # --------------------------------------------------------

                code_site_mere = self._recuperer_code_site_mere(
                    pg_cur=pg_cur,
                    codesitep=self.selected_codesitep
                )

                if not code_site_mere:
                    raise Exception(
                        f"Impossible de récupérer le code_site_mere pour le site {self.selected_codesitep}."
                    )

                codesiteps_site_mere = self._recuperer_codesiteps_du_site_mere(
                    pg_cur=pg_cur,
                    code_site_mere=code_site_mere
                )

                if not codesiteps_site_mere:
                    # Filet de sécurité : site non retrouvé comme sous-site
                    # de son propre site mère -> comportement site simple.
                    codesiteps_site_mere = [self.selected_codesitep]

                id_perm = self._generer_id_perm_suivi(
                    codesitep=code_site_mere,
                    groupe_suivi=groupe_suivi,
                    cd_nom=self.selected_cd_nom,
                    taille_maille=taille_maille,
                    id_obs=self.selected_id_obs,
                    date_creation=maintenant
                )

                suivis_existants = self._chercher_suivis_existants(
                    pg_cur=pg_cur,
                    codesitep=code_site_mere,
                    groupe_suivi=groupe_suivi,
                    cd_nom=self.selected_cd_nom,
                    taille_maille=taille_maille,
                    id_obs=self.selected_id_obs
                )

                if suivis_existants:
                    message = "Un suivi existe déjà avec les mêmes paramètres :\n\n"

                    for suivi in suivis_existants:
                        uuid_suivi_existant = suivi[0]
                        id_perm_existant = suivi[1]
                        statut_existant = suivi[2]
                        nom_fichier_existant = suivi[3]
                        date_creation_existant = suivi[4]
                        date_export_existant = suivi[5]

                        message += (
                            f"UUID : {uuid_suivi_existant}\n"
                            f"ID permanent : {id_perm_existant}\n"
                            f"Statut : {statut_existant}\n"
                            f"Fichier : {nom_fichier_existant}\n"
                            f"Date création : {date_creation_existant}\n"
                            f"Date export : {date_export_existant}\n\n"
                        )

                    message += (
                        "La création d'un nouveau suivi est annulée.\n\n"
                        "Utilisez plutôt le bouton 'Rechercher le suivi', puis 'Exporter'."
                    )

                    QMessageBox.warning(
                        self,
                        "Suivi déjà existant",
                        message
                    )

                    return
                # --------------------------------------------------------
                # 4bis. Récupération ou génération des mailles du site
                #       (tous les sous-sites du site mère)
                # --------------------------------------------------------

                mailles = self._recuperer_ou_generer_mailles_site(
                    pg_conn=pg_conn,
                    pg_cur=pg_cur,
                    codesiteps=codesiteps_site_mere,
                    code_site_mere=code_site_mere,
                    taille_maille=taille_maille
                )

                if not mailles:
                    QMessageBox.warning(
                        self,
                        "Aucune maille",
                        (
                            f"Aucune maille disponible pour le site {self.selected_codesitep} "
                            f"avec une taille de {taille_maille} m.\n\n"
                            "Le suivi ne peut pas être créé."
                        )
                    )
                    return

            

                # --------------------------------------------------------
                # 5. Insertion du suivi dans suivi_cen.suivi_espece
                # --------------------------------------------------------

                pg_cur.execute("""
                    INSERT INTO suivi_cen.suivi_espece (
                        id_perm,
                        groupe_suivi,
                        codesitep,
                        cd_nom,
                        taille_maille,
                        id_obs,
                        statut_suivi,
                        nom_fichier_gpkg
                    )
                    VALUES (
                        %s, %s, %s, %s, %s, %s, 'prepare', %s
                    )
                    RETURNING uuid_suivi;
                """, (
                    id_perm,
                    groupe_suivi,
                    code_site_mere,
                    int(self.selected_cd_nom),
                    int(taille_maille),
                    int(self.selected_id_obs),
                    nom_fichier_gpkg
                ))

                uuid_suivi = pg_cur.fetchone()[0]
                uuid_suivi_txt = str(uuid_suivi)

                # --------------------------------------------------------
                # 6. Vérification du SRID des mailles
                # --------------------------------------------------------

                srid = mailles[0][4]

                if not srid:
                    srid = 2154

                # --------------------------------------------------------
                # 7. Création de la couche mémoire mailles_suivi
                # --------------------------------------------------------

                layer_uri = f"MultiPolygon?crs=EPSG:{srid}"
                layer = QgsVectorLayer(layer_uri, "mailles_suivi", "memory")

                if not layer.isValid():
                    raise Exception("Impossible de créer la couche mémoire mailles_suivi.")

                provider = layer.dataProvider()

                provider.addAttributes([
                    QgsField("uuid_resultat", QVARIANT_STRING),
                    QgsField("uuid_suivi", QVARIANT_STRING),
                    QgsField("codesitep", QVARIANT_STRING),
                    QgsField("id_maille", QVARIANT_INT),
                    QgsField("code_maille", QVARIANT_STRING),
                    QgsField("taille_maille", QVARIANT_INT),
                    QgsField("date_obs", QVARIANT_STRING),
                    QgsField("presence_absence", QVARIANT_STRING),
                ])

                layer.updateFields()

                features = []

                for id_maille, codesitep_maille, code_maille, taille_maille_bdd, srid_bdd, geom_wkb in mailles:
                    geom = QgsGeometry()
                    geom.fromWkb(bytes(geom_wkb))

                    feat = QgsFeature(layer.fields())
                    feat.setGeometry(geom)

                    feat.setAttributes([
                        str(uuid.uuid4()),
                        uuid_suivi_txt,
                        str(codesitep_maille),
                        int(id_maille),
                        str(code_maille),
                        int(taille_maille_bdd),
                        None,
                        None,
                    ])

                    features.append(feat)

                provider.addFeatures(features)
                layer.updateExtents()

                # --------------------------------------------------------
                # 8. Création / remplacement du GeoPackage
                # --------------------------------------------------------

                if os.path.exists(chemin_gpkg):
                    os.remove(chemin_gpkg)

                options = QgsVectorFileWriter.SaveVectorOptions()
                options.driverName = "GPKG"
                options.layerName = "mailles_suivi"
                options.actionOnExistingFile = QgsVectorFileWriter.CreateOrOverwriteFile

                result = QgsVectorFileWriter.writeAsVectorFormatV3(
                    layer,
                    chemin_gpkg,
                    QgsProject.instance().transformContext(),
                    options
                )

                if result[0] != QgsVectorFileWriter.NoError:
                    raise Exception(
                        f"Erreur lors de la création du GeoPackage : {result[1]}"
                    )
                gpkg_cree_par_ce_traitement = True

                # --------------------------------------------------------
                # 9. Création de la table metadata_suivi dans le GeoPackage
                # --------------------------------------------------------

                sqlite_conn = sqlite3.connect(chemin_gpkg)
                sqlite_cur = sqlite_conn.cursor()

                sqlite_cur.execute("""
                    DROP TABLE IF EXISTS metadata_suivi;
                """)

                sqlite_cur.execute("""
                    CREATE TABLE metadata_suivi (
                        uuid_suivi TEXT PRIMARY KEY,
                        id_perm TEXT,
                        codesitep TEXT,
                        nom_site TEXT,
                        groupe_suivi TEXT,
                        cd_nom INTEGER,
                        nom_complet TEXT,
                        taille_maille INTEGER,
                        id_obs INTEGER,
                        observateur TEXT,
                        nom_fichier_gpkg TEXT,
                        date_export TEXT
                    );
                """)

                sqlite_cur.execute("""
                    INSERT INTO metadata_suivi (
                        uuid_suivi,
                        id_perm,
                        codesitep,
                        nom_site,
                        groupe_suivi,
                        cd_nom,
                        nom_complet,
                        taille_maille,
                        id_obs,
                        observateur,
                        nom_fichier_gpkg,
                        date_export
                    )
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?);
                """, (
                    uuid_suivi_txt,
                    id_perm,
                    code_site_mere,
                    self.selected_nomsitep,
                    groupe_suivi,
                    int(self.selected_cd_nom),
                    self.selected_nom_complet,
                    int(taille_maille),
                    int(self.selected_id_obs),
                    self.selected_observateur,
                    nom_fichier_gpkg,
                    maintenant.isoformat(timespec="seconds")
                ))

                sqlite_conn.commit()
                sqlite_cur.close()
                sqlite_conn.close()

                # --------------------------------------------------------
                # 10. Mise à jour du suivi en statut exporte
                # --------------------------------------------------------

                pg_cur.execute("""
                    UPDATE suivi_cen.suivi_espece
                    SET statut_suivi = 'exporte',
                        date_export = now()
                    WHERE uuid_suivi = %s;
                """, (
                    uuid_suivi,
                ))

                pg_conn.commit()

                # --------------------------------------------------------
                # 11. Message final
                # --------------------------------------------------------

                QMessageBox.information(
                    self,
                    "Suivi créé",
                    f"Le suivi a été créé avec succès.\n\n"
                    f"UUID suivi : {uuid_suivi_txt}\n"
                    f"ID permanent : {id_perm}\n\n"
                    f"Site : {self.selected_nomsitep} ({self.selected_codesitep})\n"
                    f"Groupe : {groupe_suivi}\n"
                    f"Espèce : {self.selected_nom_complet} ({self.selected_cd_nom})\n"
                    f"Observateur : {self.selected_observateur}\n"
                    f"Taille maille : {taille_maille} m\n"
                    f"Nombre de mailles : {len(mailles)}\n\n"
                    f"GeoPackage :\n{chemin_gpkg}"
                )

                self._log(
                    f"Suivi créé : {uuid_suivi_txt}\n"
                    f"ID permanent : {id_perm}\n"
                    f"GeoPackage : {chemin_gpkg}\n"
                    f"Nombre de mailles : {len(mailles)}",
                    onglet="preparation"
                )

            except Exception as e:
                if pg_conn:
                    pg_conn.rollback()

                if gpkg_cree_par_ce_traitement and chemin_gpkg and os.path.exists(chemin_gpkg):
                    try:
                        os.remove(chemin_gpkg)
                    except Exception:
                        pass

                QMessageBox.critical(
                    self,
                    "Erreur création suivi",
                    f"Impossible de créer le suivi :\n{e}"
                )

            finally:
                if pg_cur:
                    pg_cur.close()

                if pg_conn:
                    pg_conn.close()

            pass
        
        finally:
            QApplication.restoreOverrideCursor()
            progress.close()
            QApplication.processEvents()
    
    def _chercher_suivis_existants(
        self,
        pg_cur,
        codesitep,
        groupe_suivi,
        cd_nom,
        taille_maille,
        id_obs
    ):
        """
        Recherche les suivis déjà existants avec les mêmes paramètres métier.
        """

        pg_cur.execute("""
            SELECT
                uuid_suivi,
                id_perm,
                statut_suivi,
                nom_fichier_gpkg,
                date_creation,
                date_export,
                date_import
            FROM suivi_cen.suivi_espece
            WHERE codesitep = %s
            AND groupe_suivi = %s
            AND cd_nom = %s
            AND taille_maille = %s
            AND id_obs = %s
            ORDER BY date_creation DESC;
        """, (
            codesitep,
            groupe_suivi,
            int(cd_nom),
            int(taille_maille),
            int(id_obs)
        ))

        return pg_cur.fetchall()
    

    def rechercher_suivi(self):
        """
        Fonction appelée par le bouton 'Rechercher le suivi'.
        Elle recherche un suivi existant avec les paramètres sélectionnés.
        """

        if not self.selected_codesitep:
            QMessageBox.warning(self, "Site manquant", "Veuillez sélectionner un site.")
            return

        if not self.selected_cd_nom:
            QMessageBox.warning(self, "Espèce manquante", "Veuillez sélectionner une espèce.")
            return

        if not getattr(self, "selected_id_obs", None):
            QMessageBox.warning(self, "Observateur manquant", "Veuillez sélectionner un observateur.")
            return

        try:
            taille_maille = self._get_taille_maille()
        except Exception as e:
            QMessageBox.warning(self, "Taille de maille manquante", str(e))
            return

        groupe_suivi = str(self.selected_groupe_espece).strip().lower()

        pg_conn = None
        pg_cur = None

        try:
            if self.pg_service_path and os.path.exists(self.pg_service_path):
                os.environ["PGSERVICEFILE"] = self.pg_service_path

            pg_conn = psycopg2.connect(service="bd CEN (admin)")
            pg_cur = pg_conn.cursor()

            code_site_mere = self._recuperer_code_site_mere(
                pg_cur=pg_cur,
                codesitep=self.selected_codesitep
            )

            if not code_site_mere:
                QMessageBox.critical(
                    self,
                    "Erreur recherche suivi",
                    f"Impossible de récupérer le code_site_mere pour le site {self.selected_codesitep}."
                )
                return

            suivis = self._chercher_suivis_existants(
                pg_cur=pg_cur,
                codesitep=code_site_mere,
                groupe_suivi=groupe_suivi,
                cd_nom=self.selected_cd_nom,
                taille_maille=taille_maille,
                id_obs=self.selected_id_obs
            )

            if not suivis:
                self.selected_uuid_suivi_export = None
                self.selected_id_perm_export = None
                self.selected_statut_suivi_export = None

                QMessageBox.information(
                    self,
                    "Aucun suivi",
                    "Aucun suivi existant ne correspond à ces paramètres."
                )
                return

            # Pour commencer, on prend le suivi le plus récent
            suivi = suivis[0]

            self.selected_uuid_suivi_export = suivi[0]
            self.selected_id_perm_export = suivi[1]
            self.selected_statut_suivi_export = suivi[2]

            QMessageBox.information(
                self,
                "Suivi trouvé",
                f"Un suivi existant a été trouvé.\n\n"
                f"UUID : {suivi[0]}\n"
                f"ID permanent : {suivi[1]}\n"
                f"Statut : {suivi[2]}\n"
                f"Fichier GeoPackage : {suivi[3]}\n"
                f"Date création : {suivi[4]}\n"
                f"Date export : {suivi[5]}\n"
                f"Date import : {suivi[6]}\n\n"
                f"Vous pouvez maintenant utiliser le bouton Exporter."
            )

        except Exception as e:
            QMessageBox.critical(
                self,
                "Erreur recherche suivi",
                f"Impossible de rechercher le suivi :\n{e}"
            )

        finally:
            if pg_cur:
                pg_cur.close()

            if pg_conn:
                pg_conn.close()

