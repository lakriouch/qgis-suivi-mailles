    def lancer_mode_suivi_terrain(self):
        """
        Lance le mode clic pour renseigner presence_absence.
        """

        if not self.layer_suivi_terrain or not self.layer_suivi_terrain.isValid():
            QMessageBox.warning(
                self,
                "Aucune couche",
                "Veuillez d'abord charger le GeoPackage terrain."
            )
            return

        layer = self.layer_suivi_terrain

        if not layer.isEditable():
            if not layer.startEditing():
                QMessageBox.critical(
                    self,
                    "Édition impossible",
                    "Impossible de passer la couche en mode édition."
                )
                return

        canvas = self.iface.mapCanvas()

        self.maptool_suivi_terrain = QgsMapToolIdentifyFeature(
            canvas,
            layer
        )

        self.maptool_suivi_terrain.featureIdentified.connect(
            self._maille_cliquee_suivi_terrain
        )

        canvas.setMapTool(self.maptool_suivi_terrain)

        self.suivi_terrain_actif = True

        self.btn_lancer_suivi.setEnabled(False)
        self.btn_arreter_suivi.setEnabled(True)

        self._log_terrain(
            "Mode clic activé.\n"
            "Cliquez sur une maille dans QGIS pour renseigner présence ou absence."
        )
    def arreter_mode_suivi_terrain(self):
        """
        Arrête le mode clic de suivi.
        """

        canvas = self.iface.mapCanvas()

        if self.maptool_suivi_terrain:
            try:
                self.maptool_suivi_terrain.featureIdentified.disconnect(
                    self._maille_cliquee_suivi_terrain
                )
            except Exception:
                pass

            try:
                canvas.unsetMapTool(self.maptool_suivi_terrain)
            except Exception:
                pass

            self.maptool_suivi_terrain = None

        self.suivi_terrain_actif = False

        self.btn_lancer_suivi.setEnabled(True)
        self.btn_arreter_suivi.setEnabled(False)

        self._log_terrain("Mode clic arrêté.")

    def _sauvegarder_style_presence_absence(self, layer):
        """
        Sauvegarde le style présence/absence.

        Deux sauvegardes sont tentées :
        - dans la base GeoPackage via saveStyleToDatabase ;
        - dans un fichier .qml à côté du GeoPackage.
        """

        if not layer or not layer.isValid():
            return

        # --------------------------------------------------------
        # 1. Sauvegarde du style dans le GeoPackage si possible
        # --------------------------------------------------------

        try:
            resultat = layer.saveStyleToDatabase(
                "style_presence_absence",
                "Style présence/absence : vert=1, rouge=0, transparent=vide",
                True,
                ""
            )

            self._log_terrain(
                "Style présence/absence sauvegardé dans le GeoPackage si le fournisseur le permet."
            )

        except Exception as e:
            self._log_terrain(
                f"Attention : impossible de sauvegarder le style dans le GeoPackage : {e}"
            )

        # --------------------------------------------------------
        # 2. Sauvegarde de secours dans un fichier QML
        # --------------------------------------------------------

        try:
            if self.chemin_gpkg_terrain:
                dossier = os.path.dirname(self.chemin_gpkg_terrain)
                nom_base = os.path.splitext(os.path.basename(self.chemin_gpkg_terrain))[0]

                chemin_qml = os.path.join(
                    dossier,
                    f"{nom_base}_style_mailles_suivi.qml"
                )

                layer.saveNamedStyle(chemin_qml)

                self._log_terrain(
                    f"Style également sauvegardé en fichier QML : {chemin_qml}"
                )

        except Exception as e:
            self._log_terrain(
                f"Attention : impossible de sauvegarder le style QML : {e}"
            )


    def sauvegarder_geopackage_terrain(self):
        """
        Sauvegarde les modifications dans le GeoPackage
        et réapplique le style présence/absence.
        """

        layer = self.layer_suivi_terrain

        if not layer or not layer.isValid():
            QMessageBox.warning(
                self,
                "Aucune couche",
                "Aucune couche terrain n'est chargée."
            )
            return

        if not layer.isEditable():
            QMessageBox.information(
                self,
                "Aucune modification",
                "La couche n'est pas en mode édition. Aucune modification à sauvegarder."
            )

            # Même si pas en édition, on réapplique le style
            self._appliquer_style_presence_absence(layer)
            return

        ok = layer.commitChanges()

        if not ok:
            erreurs = "\n".join(layer.commitErrors())

            QMessageBox.critical(
                self,
                "Erreur de sauvegarde",
                (
                    "Impossible de sauvegarder les modifications dans le GeoPackage.\n\n"
                    f"{erreurs}"
                )
            )

            self._log_terrain(
                "Erreur lors de la sauvegarde du GeoPackage :\n"
                f"{erreurs}"
            )

            return

        # réappliquer le style après commitChanges()
        self._appliquer_style_presence_absence(layer)

        # sauvegarder le style dans le GeoPackage / QML
        self._sauvegarder_style_presence_absence(layer)

        layer.triggerRepaint()

        try:
            self.iface.layerTreeView().refreshLayerSymbology(layer.id())
        except Exception:
            pass

        try:
            self.iface.mapCanvas().refresh()
        except Exception:
            pass

        self._log_terrain("GeoPackage sauvegardé avec succès. Style réappliqué.")

        QMessageBox.information(
            self,
            "Sauvegarde réussie",
            "Les modifications ont été sauvegardées dans le GeoPackage."
        )

        if self.suivi_terrain_actif:
            layer.startEditing()



    def _maille_cliquee_suivi_terrain(self, feature):
        """
        Modifie automatiquement presence_absence à chaque clic sur une maille.
        """

        layer = self.layer_suivi_terrain

        if not layer or not layer.isValid():
            return

        idx_presence = layer.fields().indexFromName("presence_absence")
        idx_date_obs = layer.fields().indexFromName("date_obs")

        if idx_presence == -1:
            QMessageBox.critical(
                self,
                "Champ manquant",
                "Le champ presence_absence est introuvable."
            )
            return

        if not layer.isEditable():
            if not layer.startEditing():
                QMessageBox.critical(
                    self,
                    "Édition impossible",
                    "Impossible de passer la couche en mode édition."
                )
                return

        code_maille = feature["code_maille"]
        valeur_actuelle = feature["presence_absence"]

        # --------------------------------------------------------
        # Normalisation de la valeur actuelle
        # --------------------------------------------------------

        if valeur_actuelle is None:
            valeur_normale = None
        else:
            valeur_normale = str(valeur_actuelle).strip().lower()

            if valeur_normale in ("", "null", "none"):
                valeur_normale = None

        # --------------------------------------------------------
        # Cycle de clic
        # --------------------------------------------------------

        if valeur_normale is None:
            nouvelle_valeur = "1"
            libelle_valeur = "présence"

        elif valeur_normale in ("1", "presence", "présence"):
            nouvelle_valeur = "0"
            libelle_valeur = "absence"

        elif valeur_normale in ("0", "absence"):
            nouvelle_valeur = None
            libelle_valeur = "annulé"

        else:
            nouvelle_valeur = "1"
            libelle_valeur = "présence"

        # --------------------------------------------------------
        # Mise à jour du champ presence_absence
        # --------------------------------------------------------

        ok_presence = layer.changeAttributeValue(
            feature.id(),
            idx_presence,
            nouvelle_valeur
        )

        # --------------------------------------------------------
        # Mise à jour du champ date_obs
        # --------------------------------------------------------

        if idx_date_obs != -1:
            if nouvelle_valeur is None:
                layer.changeAttributeValue(
                    feature.id(),
                    idx_date_obs,
                    None
                )
            else:
                layer.changeAttributeValue(
                    feature.id(),
                    idx_date_obs,
                    datetime.now().date().isoformat()
                )

        # --------------------------------------------------------
        # Rafraîchissement visuel
        # --------------------------------------------------------

        layer.triggerRepaint()

        try:
            self.iface.layerTreeView().refreshLayerSymbology(layer.id())
        except Exception:
            pass

        try:
            self.iface.mapCanvas().refresh()
        except Exception:
            pass

        # --------------------------------------------------------
        # Message utilisateur
        # --------------------------------------------------------

        if ok_presence:
            self._log_terrain(
                f"Maille {code_maille} : {libelle_valeur} "
                f"presence_absence = {nouvelle_valeur}"
            )
        else:
            self._log_terrain(
                f"Erreur : impossible de modifier la maille {code_maille}."
            )


    def _appliquer_style_presence_absence(self, layer):
        """
        Applique le style de la couche mailles_suivi :

        - presence_absence = 1 : vert
        - presence_absence = 0 : rouge
        - NULL / vide / autre : remplissage transparent
        """

        if not layer or not layer.isValid():
            return

        # ========================================================
        # Règle 1 : Présence = vert
        # ========================================================

        symbole_presence = QgsSymbol.defaultSymbol(layer.geometryType())

        # Remplissage vert semi-transparent
        symbole_presence.setColor(QColor(0, 180, 0, 150))

        if symbole_presence.symbolLayerCount() > 0:
            sl = symbole_presence.symbolLayer(0)

            if hasattr(sl, "setStrokeColor"):
                sl.setStrokeColor(QColor(0, 100, 0, 220))

            if hasattr(sl, "setStrokeWidth"):
                sl.setStrokeWidth(0.4)

        regle_presence = QgsRuleBasedRenderer.Rule(symbole_presence)
        regle_presence.setLabel("Présence")
        regle_presence.setFilterExpression(
            "trim(to_string(\"presence_absence\")) = '1'"
        )

        # ========================================================
        # Règle 2 : Absence = rouge
        # ========================================================

        symbole_absence = QgsSymbol.defaultSymbol(layer.geometryType())

        # Remplissage rouge semi-transparent
        symbole_absence.setColor(QColor(220, 0, 0, 150))

        if symbole_absence.symbolLayerCount() > 0:
            sl = symbole_absence.symbolLayer(0)

            if hasattr(sl, "setStrokeColor"):
                sl.setStrokeColor(QColor(140, 0, 0, 220))

            if hasattr(sl, "setStrokeWidth"):
                sl.setStrokeWidth(0.4)

        regle_absence = QgsRuleBasedRenderer.Rule(symbole_absence)
        regle_absence.setLabel("Absence")
        regle_absence.setFilterExpression(
            "trim(to_string(\"presence_absence\")) = '0'"
        )

        # ========================================================
        # Règle 3 : Non renseigné = remplissage transparent
        # ========================================================

        symbole_non_renseigne = QgsSymbol.defaultSymbol(layer.geometryType())

        # Remplissage totalement transparent
        symbole_non_renseigne.setColor(QColor(255, 255, 255, 0))

        if symbole_non_renseigne.symbolLayerCount() > 0:
            sl = symbole_non_renseigne.symbolLayer(0)

            # Contour gris léger pour les limites des mailles
            if hasattr(sl, "setStrokeColor"):
                sl.setStrokeColor(QColor(120, 120, 120, 120))

            if hasattr(sl, "setStrokeWidth"):
                sl.setStrokeWidth(0.25)

        regle_non_renseigne = QgsRuleBasedRenderer.Rule(symbole_non_renseigne)
        regle_non_renseigne.setLabel("Non renseigné")
        regle_non_renseigne.setFilterExpression(
            "\"presence_absence\" IS NULL "
            "OR trim(to_string(\"presence_absence\")) = '' "
            "OR lower(trim(to_string(\"presence_absence\"))) = 'null' "
            "OR lower(trim(to_string(\"presence_absence\"))) = 'none' "
            "OR (trim(to_string(\"presence_absence\")) <> '1' "
            "AND trim(to_string(\"presence_absence\")) <> '0')"
        )

        # ========================================================
        # Construction du renderer
        # ========================================================

        racine = QgsRuleBasedRenderer.Rule(None)
        racine.appendChild(regle_presence)
        racine.appendChild(regle_absence)
        racine.appendChild(regle_non_renseigne)

        renderer = QgsRuleBasedRenderer(racine)

        layer.setRenderer(renderer)
        layer.triggerRepaint()

        try:
            self.iface.layerTreeView().refreshLayerSymbology(layer.id())
        except Exception:
            pass

        try:
            self.iface.mapCanvas().refresh()
        except Exception:
            pass


    def _charger_table_metadata_suivi_qgis(self, chemin_gpkg):
        """
        Charge la table metadata_suivi du GeoPackage dans le projet QGIS.
        Cette table est non spatiale.
        """

        nom_table = "metadata_suivi"
        uri = f"{chemin_gpkg}|layername={nom_table}"

        table = QgsVectorLayer(uri, nom_table, "ogr")

        if not table.isValid():
            self._log_terrain(
                "Attention : la table metadata_suivi n'a pas pu être chargée dans QGIS."
            )
            return None

        self.table_metadata_terrain = table

        QgsProject.instance().addMapLayer(table)

        self._log_terrain(
            "Table metadata_suivi chargée dans QGIS."
        )

        return table


