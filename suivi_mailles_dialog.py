    def _filtrer(self, texte):
        """
        Filtre les sites pour l'autocomplétion du champ self.site.

        Recherche :
        - sans accents
        - sans tenir compte des majuscules/minuscules
        - n'importe où dans le nom du site
        - dans les communes
        - dans le code site
        - avec plusieurs mots dans n'importe quel ordre
        """

        # On réinitialise la sélection courante
        self.selected_codesitep = None
        self.selected_nomsitep = None
        self.selected_communes = None

        self.site.setProperty("codesitep", None)
        self.site.setProperty("nomsitep", None)
        self.site.setProperty("communes", None)

        texte_normalise = self._normaliser_texte(texte)

        # Si moins de 3 caractères, on ne propose rien
        if len(texte_normalise) < 3:
            self._site_model.setStringList([])
            self._site_by_label = {}
            return

        mots_recherche = texte_normalise.split()

        labels = []
        self._site_by_label = {}

        for site_data in self._all_sites:
            codesitep = site_data["codesitep"]
            nomsitep = site_data["nomsitep"]
            communes = site_data["communes"]

            contenu = self._normaliser_texte(
                f"{nomsitep} {communes} {codesitep}"
            )

            # Tous les mots tapés doivent être présents quelque part
            correspond = all(mot in contenu for mot in mots_recherche)

            if correspond:
                if communes:
                    label = f"{nomsitep} — {communes} ({codesitep})"
                else:
                    label = f"{nomsitep} ({codesitep})"

                labels.append(label)

                # Permet de retrouver le site sélectionné ensuite
                self._site_by_label[label] = site_data

                # Limite pour éviter une liste trop longue
                if len(labels) >= 50:
                    break

        self._site_model.setStringList(labels)

        if labels:
            self._site_completer.complete()


