    def _generer_id_perm_suivi(
        self,
        codesitep,
        groupe_suivi,
        cd_nom,
        taille_maille,
        id_obs,
        date_creation
    ):
        """
        Génère un identifiant permanent lisible pour le suivi.

        Exemple :
        SUIVI_FR1234_FAUNE_60612_100M_OBS25_20260716_153000
        """

        codesitep_txt = str(codesitep).strip().replace(" ", "_")
        groupe_txt = str(groupe_suivi).strip().upper().replace(" ", "_")
        cd_nom_txt = str(cd_nom).strip()
        taille_txt = str(taille_maille).strip()
        id_obs_txt = str(id_obs).strip()

        date_txt = date_creation.strftime("%Y%m%d_%H%M%S")

        id_perm = (
            f"SUIVI_{codesitep_txt}_"
            f"{groupe_txt}_"
            f"{cd_nom_txt}_"
            f"{taille_txt}M_"
            f"OBS{id_obs_txt}_"
            f"{date_txt}"
        )

        return id_perm

