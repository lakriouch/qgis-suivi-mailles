    def _charger_observateurs_depuis_bdd(self):
        """
        Charge les observateurs depuis bdfauneflore.w_observateur.

        Conditions :
        - observateur_virtreel = 'R'
        - observateur_organisme correspond à CEN hauts-de-france
        sans tenir compte des majuscules, tirets, espaces.
        """

        try:
            if self.pg_service_path and os.path.exists(self.pg_service_path):
                os.environ["PGSERVICEFILE"] = self.pg_service_path

            conn = psycopg2.connect(service="bd CEN (admin)")
            cur = conn.cursor()

            cur.execute("""
                SELECT DISTINCT
                    id,
                    titre,
                    observateur_organisme,
                    observateur_virtreel
                FROM bdfauneflore.w_observateur
                WHERE titre IS NOT NULL
                AND upper(trim(observateur_virtreel)) = 'R'
                ORDER BY titre ASC;
            """)

            rows = cur.fetchall()

            cur.close()
            conn.close()

            self._all_observateurs = []

            # Référence attendue, normalisée sans espaces
            organisme_reference = self._normaliser_texte("CEN hauts-de-france").replace(" ", "")

            titres_deja_ajoutes = set()

            for id_obs,titre, observateur_organisme, observateur_virtreel in rows:
                titre = titre or ""
                observateur_organisme = observateur_organisme or ""

                # Normalisation souple :
                # "CEN hauts-de-france" -> "cenhautsdefrance"
                # "cen hauts de france" -> "cenhautsdefrance"
                # "CEN-HAUTS-DE-FRANCE" -> "cenhautsdefrance"
                organisme_normalise = self._normaliser_texte(observateur_organisme).replace(" ", "")

                if organisme_normalise != organisme_reference:
                    continue

                if not titre.strip():
                    continue

                # Évite les doublons
                titre_key = self._normaliser_texte(titre)

                if titre_key in titres_deja_ajoutes:
                    continue

                titres_deja_ajoutes.add(titre_key)

                self._all_observateurs.append({
                    "id_obs":id_obs,
                    "titre": titre.strip(),
                    "observateur_organisme": observateur_organisme,
                    "observateur_virtreel": observateur_virtreel,
                })

            print(f"{len(self._all_observateurs)} observateur(s) chargé(s)")

        except Exception as e:
            QMessageBox.critical(
                self,
                "Erreur BDD",
                f"Impossible de charger la liste des observateurs :\n{e}"
            )

