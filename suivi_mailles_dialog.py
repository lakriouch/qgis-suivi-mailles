    def _normaliser_texte(self, texte):
        """
        Normalise un texte pour la recherche :
        - None devient ""
        - minuscules
        - suppression des accents
        - remplacement œ -> oe, æ -> ae
        - remplacement ponctuation/tirets/apostrophes par espaces
        - suppression espaces multiples
        """
        import unicodedata
        import re

        if texte is None:
            return ""

        texte = str(texte).strip().lower()

        # Cas non gérés automatiquement par unicodedata
        texte = texte.replace("œ", "oe")
        texte = texte.replace("æ", "ae")

        # Décompose les accents
        texte = unicodedata.normalize("NFD", texte)

        # Supprime les accents
        texte = "".join(
            caractere for caractere in texte
            if unicodedata.category(caractere) != "Mn"
        )

        # Remplace tout ce qui n'est pas lettre/chiffre par un espace
        texte = re.sub(r"[^a-z0-9]+", " ", texte)

        # Nettoie les espaces multiples
        texte = re.sub(r"\s+", " ", texte).strip()

        return texte

