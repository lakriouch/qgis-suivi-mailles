    def open_qgis_gps_panel(self):
        """
        Ouvrir le panneau Information GPS de QGIS.
        Retourne True si le panneau est ouvert, False sinon.
        """

        main_window = self.iface.mainWindow()

        # 1. Chercher un dock GPS déjà existant
        try:
            docks = main_window.findChildren(QDockWidget)

            for dock in docks:
                title = dock.windowTitle().lower()
                name = dock.objectName().lower()

                if "gps" in title or "gps" in name or "gnss" in title or "gnss" in name:
                    dock.show()
                    dock.raise_()
                    return True

        except Exception:
            pass

        # 2. Chercher une action QGIS connue pour afficher le panneau GPS
        possible_action_names = [
            "mActionShowGpsInformation",
            "mActionGpsInformation",
            "mActionGPSInformation",
            "mActionToggleGpsInformation",
            "mActionToggleGPSInformation",
            "mActionShowGPSInformation",
        ]

        try:
            for action_name in possible_action_names:
                action = main_window.findChild(QAction, action_name)

                if action:
                    action.trigger()
                    return True

        except Exception:
            pass

        # 3. Chercher une action par son texte
        try:
            actions = main_window.findChildren(QAction)

            for action in actions:
                text = action.text().replace("&", "").lower()
                name = action.objectName().lower()

                if (
                    "information gps" in text
                    or "informations gps" in text
                    or "gps information" in text
                    or "gps" in name
                    or "gnss" in name
                ):
                    action.trigger()
                    return True

        except Exception:
            pass

        # 4. créer directement le widget GPS si disponible
        try:
            from qgis.gui import QgsGpsInformationWidget

            if not hasattr(self, "gps_dock") or self.gps_dock is None:
                self.gps_dock = QDockWidget("Information GPS", main_window)
                self.gps_dock.setObjectName("suivi_mailles_gps_dock")

                self.gps_widget = QgsGpsInformationWidget(
                    self.iface.mapCanvas(),
                    self.gps_dock
                )

                self.gps_dock.setWidget(self.gps_widget)
                main_window.addDockWidget(QT_LEFT_DOCK_WIDGET_AREA, self.gps_dock)

            self.gps_dock.show()
            self.gps_dock.raise_()
            return True

        except Exception:
            pass

        return False



