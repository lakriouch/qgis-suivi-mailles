    def lire_geopackage_import(self):
        """
        Lit la table metadata_suivi du GeoPackage et affiche
        les informations principales dans l'interface.
        """

        chemin = self.le_fichier_gpkg_import.text().strip()

        if not chemin:
            QMessageBox.warning(
                self,
                "GeoPackage manquant",
                "Veuillez sélectionner un GeoPackage."
            )
            return

        chemin = os.path.abspath(chemin)

        if not os.path.isfile(chemin):
            QMessageBox.warning(
                self,
                "Fichier introuvable",
                f"Le fichier n'existe pas :\n\n{chemin}"
            )
            return

        if not chemin.lower().endswith(".gpkg"):
            QMessageBox.warning(
                self,
                "Fichier invalide",
                "Le fichier sélectionné n'est pas un GeoPackage."
            )
            return

        sqlite_conn = None

        try:
            sqlite_conn = sqlite3.connect(chemin)
            sqlite_conn.row_factory = sqlite3.Row
            sqlite_cur = sqlite_conn.cursor()

            # Vérification des tables obligatoires
            sqlite_cur.execute("""
                SELECT name
                FROM sqlite_master
                WHERE type = 'table'
                AND name IN ('metadata_suivi', 'mailles_suivi');
            """)

            tables = {row[0] for row in sqlite_cur.fetchall()}

            if "metadata_suivi" not in tables:
                raise Exception(
                    "La table metadata_suivi est absente du GeoPackage."
                )

            if "mailles_suivi" not in tables:
                raise Exception(
                    "La couche mailles_suivi est absente du GeoPackage."
                )

            # Lecture des métadonnées
            sqlite_cur.execute("""
                SELECT
                    uuid_suivi,
                    id_perm,
                    codesitep,
                    nom_site,
                    groupe_suivi,
                    cd_nom,
                    nom_complet,
                    taille_maille,
                    id_obs,
                    observateur,
                    nom_fichier_gpkg,
                    date_export
                FROM metadata_suivi
                LIMIT 1;
            """)

            row = sqlite_cur.fetchone()

            if row is None:
                raise Exception(
                    "La table metadata_suivi ne contient aucune ligne."
                )

            self.metadata_suivi_import = dict(row)
            self.chemin_gpkg_import = chemin
            self.controle_import_valide = False

            # Affichage des métadonnées
            uuid_suivi = self.metadata_suivi_import["uuid_suivi"]
            codesitep = self.metadata_suivi_import["codesitep"]
            nom_site = self.metadata_suivi_import["nom_site"]
            cd_nom = self.metadata_suivi_import["cd_nom"]
            nom_complet = self.metadata_suivi_import["nom_complet"]
            taille_maille = self.metadata_suivi_import["taille_maille"]

            self.le_uuid_suivi_import.setText(
                str(uuid_suivi or "")
            )

            self.le_site_import.setText(
                f"{nom_site or ''} ({codesitep or ''})"
            )

            self.le_espece_import.setText(
                f"{nom_complet or ''} ({cd_nom or ''})"
            )

            self.le_taille_maille_import.setText(
                f"{taille_maille} m" if taille_maille is not None else ""
            )

            # Recherche des dates renseignées dans les mailles
            sqlite_cur.execute("""
                SELECT DISTINCT trim(CAST(date_obs AS TEXT))
                FROM mailles_suivi
                WHERE date_obs IS NOT NULL
                AND trim(CAST(date_obs AS TEXT)) <> ''
                ORDER BY 1;
            """)

            dates_obs = [row[0] for row in sqlite_cur.fetchall()]

            if len(dates_obs) == 1:
                texte_date = dates_obs[0]
            elif len(dates_obs) > 1:
                texte_date = f"Plusieurs dates ({len(dates_obs)})"
            else:
                texte_date = "Non renseignée"

            self.le_date_obs_import.setText(texte_date)

            # Les compteurs seront remplis à l'étape de contrôle
            self.le_nb_mailles_total_import.clear()
            self.le_nb_mailles_renseignees_import.clear()

            self.btn_transferer_resultats.setEnabled(False)

            self._log_import(
                "Lecture du GeoPackage terminée.\n"
                f"- UUID suivi : {uuid_suivi}\n"
                f"- Site : {nom_site} ({codesitep})\n"
                f"- Espèce : {nom_complet} ({cd_nom})\n"
                f"- Taille de maille : {taille_maille} m\n"
                f"- Date : {texte_date}"
            )

        except Exception as e:
            self.metadata_suivi_import = {}
            self.controle_import_valide = False

            self.btn_transferer_resultats.setEnabled(False)

            self._log_import(
                f"Erreur de lecture du GeoPackage : {e}"
            )

            QMessageBox.critical(
                self,
                "Erreur de lecture",
                f"Impossible de lire le GeoPackage :\n\n{e}"
            )

        finally:
            if sqlite_conn is not None:
                sqlite_conn.close()

    # Fonction controler 

    def controler_geopackage_import(self):
        """
        Contrôle les métadonnées et les mailles renseignées
        avant leur transfert dans PostgreSQL.
        """

        chemin = self.le_fichier_gpkg_import.text().strip()

        self.controle_import_valide = False
        self.donnees_mailles_import = []
        self.btn_transferer_resultats.setEnabled(False)

        if not chemin or not os.path.isfile(chemin):
            QMessageBox.warning(
                self,
                "GeoPackage introuvable",
                "Veuillez sélectionner et lire un GeoPackage valide."
            )
            return

        if not self.metadata_suivi_import:
            QMessageBox.warning(
                self,
                "Métadonnées non lues",
                "Veuillez d'abord cliquer sur « Lire le GeoPackage »."
            )
            return

        sqlite_conn = None

        try:
            sqlite_conn = sqlite3.connect(chemin)
            sqlite_conn.row_factory = sqlite3.Row
            sqlite_cur = sqlite_conn.cursor()

            # --------------------------------------------------------
            # 1. Vérification des champs de mailles_suivi
            # --------------------------------------------------------

            sqlite_cur.execute("PRAGMA table_info(mailles_suivi);")
            champs_existants = {
                row["name"] for row in sqlite_cur.fetchall()
            }

            champs_obligatoires = {
                "uuid_resultat",
                "uuid_suivi",
                "id_maille",
                "code_maille",
                "taille_maille",
                "date_obs",
                "presence_absence",
            }

            champs_manquants = champs_obligatoires - champs_existants

            if champs_manquants:
                raise Exception(
                    "Champs manquants dans mailles_suivi : "
                    + ", ".join(sorted(champs_manquants))
                )

            # --------------------------------------------------------
            # 2. Lecture de toutes les mailles
            # --------------------------------------------------------

            sqlite_cur.execute("""
                SELECT
                    uuid_resultat,
                    uuid_suivi,
                    id_maille,
                    code_maille,
                    taille_maille,
                    date_obs,
                    presence_absence
                FROM mailles_suivi;
            """)

            mailles = sqlite_cur.fetchall()
            nb_total = len(mailles)

            erreurs = []
            mailles_renseignees = []

            uuid_suivi_metadata = str(
                self.metadata_suivi_import.get("uuid_suivi") or ""
            ).strip()

            if not uuid_suivi_metadata:
                erreurs.append(
                    "L'UUID du suivi est absent de metadata_suivi."
                )
            else:
                try:
                    uuid.UUID(uuid_suivi_metadata)
                except (ValueError, TypeError, AttributeError):
                    erreurs.append(
                        "L'UUID du suivi présent dans metadata_suivi est invalide."
                    )

            uuid_resultats_vus = set()
            id_mailles_vus = set()

            # --------------------------------------------------------
            # 3. Contrôle de chaque maille
            # --------------------------------------------------------

            for numero, maille in enumerate(mailles, start=1):
                valeur_presence = maille["presence_absence"]

                if valeur_presence is None:
                    presence = ""
                else:
                    presence = str(valeur_presence).strip().lower()

                # Une maille vide est autorisée et n'est pas transférée
                if presence in ("", "null", "none"):
                    continue

                # Toute autre valeur que 0 ou 1 est une erreur
                if presence not in ("0", "1"):
                    erreurs.append(
                        f"Ligne {numero} : presence_absence doit valoir 0 ou 1, "
                        f"valeur trouvée : {valeur_presence}."
                    )
                    continue

                uuid_resultat = str(
                    maille["uuid_resultat"] or ""
                ).strip()

                uuid_suivi_maille = str(
                    maille["uuid_suivi"] or ""
                ).strip()

                id_maille = maille["id_maille"]
                code_maille = str(
                    maille["code_maille"] or ""
                ).strip()

                taille_maille = maille["taille_maille"]
                date_obs = str(
                    maille["date_obs"] or ""
                ).strip()

                # UUID du résultat
                if not uuid_resultat:
                    erreurs.append(
                        f"Ligne {numero} : uuid_resultat est manquant."
                    )
                else:
                    try:
                        uuid.UUID(uuid_resultat)
                    except (ValueError, TypeError, AttributeError):
                        erreurs.append(
                            f"Ligne {numero} : uuid_resultat est invalide."
                        )

                    if uuid_resultat in uuid_resultats_vus:
                        erreurs.append(
                            f"Ligne {numero} : uuid_resultat est présent plusieurs fois."
                        )

                    uuid_resultats_vus.add(uuid_resultat)

                # UUID du suivi
                if not uuid_suivi_maille:
                    erreurs.append(
                        f"Ligne {numero} : uuid_suivi est manquant."
                    )
                elif uuid_suivi_maille != uuid_suivi_metadata:
                    erreurs.append(
                        f"Ligne {numero} : uuid_suivi ne correspond pas "
                        "aux métadonnées du suivi."
                    )

                # Identifiant de maille
                if id_maille is None:
                    erreurs.append(
                        f"Ligne {numero} : id_maille est manquant."
                    )
                else:
                    if id_maille in id_mailles_vus:
                        erreurs.append(
                            f"Ligne {numero} : id_maille {id_maille} "
                            "est présent plusieurs fois."
                        )

                    id_mailles_vus.add(id_maille)

                if not code_maille:
                    erreurs.append(
                        f"Ligne {numero} : code_maille est manquant."
                    )

                if taille_maille is None:
                    erreurs.append(
                        f"Ligne {numero} : taille_maille est manquante."
                    )

                if not date_obs:
                    erreurs.append(
                        f"Ligne {numero} : date_obs est manquante."
                    )

                mailles_renseignees.append({
                    "uuid_resultat": uuid_resultat,
                    "uuid_suivi": uuid_suivi_maille,
                    "id_maille": id_maille,
                    "code_maille": code_maille,
                    "taille_maille": taille_maille,
                    "date_obs": date_obs,
                    "presence_absence": presence,
                })

            # --------------------------------------------------------
            # 4. Affichage des compteurs
            # --------------------------------------------------------

            nb_renseignees = len(mailles_renseignees)

            self.le_nb_mailles_total_import.setText(str(nb_total))
            self.le_nb_mailles_renseignees_import.setText(
                str(nb_renseignees)
            )

            if nb_total == 0:
                erreurs.append(
                    "La couche mailles_suivi ne contient aucune maille."
                )

            if nb_renseignees == 0:
                erreurs.append(
                    "Aucune maille n'est renseignée avec une présence ou une absence."
                )

            # --------------------------------------------------------
            # 5. Résultat du contrôle
            # --------------------------------------------------------

            if erreurs:
                self._log_import(
                    "Contrôle terminé avec des erreurs :\n- "
                    + "\n- ".join(erreurs)
                )

                QMessageBox.warning(
                    self,
                    "Contrôle non valide",
                    f"{len(erreurs)} erreur(s) ont été détectées.\n\n"
                    "Consultez le résumé de l'import."
                )
                return

            self.donnees_mailles_import = mailles_renseignees
            self.controle_import_valide = True
            self.btn_transferer_resultats.setEnabled(True)

            nb_non_renseignees = nb_total - nb_renseignees

            self._log_import(
                "Contrôle terminé avec succès.\n"
                f"- Nombre total de mailles : {nb_total}\n"
                f"- Mailles renseignées : {nb_renseignees}\n"
                f"- Mailles non renseignées : {nb_non_renseignees}\n"
                "Le transfert dans la base est maintenant autorisé."
            )

            QMessageBox.information(
                self,
                "Contrôle valide",
                f"Le GeoPackage est valide.\n\n"
                f"Mailles renseignées à transférer : {nb_renseignees}"
            )

        except Exception as e:
            self.controle_import_valide = False
            self.donnees_mailles_import = []
            self.btn_transferer_resultats.setEnabled(False)

            self._log_import(
                f"Erreur pendant le contrôle : {e}"
            )

            QMessageBox.critical(
                self,
                "Erreur de contrôle",
                f"Impossible de contrôler le GeoPackage :\n\n{e}"
            )

        finally:
            if sqlite_conn is not None:
                sqlite_conn.close()

    def _generer_id_perm_observation(
        self,
        id_perm_suivi,
        id_maille,
        uuid_resultat
    ):
        """
        Génère un identifiant permanent et déterministe
        pour une observation de maille.
        """

        id_perm_suivi_txt = str(id_perm_suivi or "").strip()
        id_maille_txt = str(id_maille or "").strip()
        uuid_resultat_txt = str(uuid_resultat or "").strip()

        if not id_perm_suivi_txt:
            raise Exception(
                "Impossible de générer l'id_perm de l'observation : "
                "id_perm du suivi manquant."
            )

        if not id_maille_txt:
            raise Exception(
                "Impossible de générer l'id_perm de l'observation : "
                "id_maille manquant."
            )

        try:
            uuid_resultat_txt = str(
                uuid.UUID(uuid_resultat_txt)
            ).upper()
        except (ValueError, TypeError, AttributeError):
            raise Exception(
                f"uuid_resultat invalide : {uuid_resultat_txt}"
            )

        id_perm_suivi_txt = re.sub(
            r"[^A-Za-z0-9_-]+",
            "_",
            id_perm_suivi_txt
        ).strip("_").upper()

        id_perm = (
            f"OBS_{id_perm_suivi_txt}_"
            f"MAILLE{id_maille_txt}_"
            f"R{uuid_resultat_txt}"
        )

        if len(id_perm) > 255:
            raise Exception(
                "L'identifiant permanent généré dépasse 255 caractères : "
                f"{len(id_perm)} caractères."
            )

        return id_perm



    # Fonction transferer dans la base 
    def transferer_resultats_import(self):
        """
        Transfère les mailles renseignées du GeoPackage vers
        suivi_cen.observation_maille.
        """

        # --------------------------------------------------------
        # 1. Vérifications préalables
        # --------------------------------------------------------

        if not self.controle_import_valide:
            QMessageBox.warning(
                self,
                "Contrôle obligatoire",
                "Veuillez contrôler le GeoPackage avant de transférer les données."
            )
            return

        if not self.metadata_suivi_import:
            QMessageBox.warning(
                self,
                "Métadonnées absentes",
                "Les métadonnées du suivi ne sont pas disponibles."
            )
            return

        if not self.donnees_mailles_import:
            QMessageBox.warning(
                self,
                "Aucune donnée",
                "Aucune maille renseignée n'est disponible pour le transfert."
            )
            return

        chemin_gpkg = self.le_fichier_gpkg_import.text().strip()

        if not chemin_gpkg or not os.path.isfile(chemin_gpkg):
            QMessageBox.warning(
                self,
                "GeoPackage introuvable",
                "Le GeoPackage sélectionné est introuvable."
            )
            return

        metadata = self.metadata_suivi_import
        id_perm_suivi = str(metadata.get("id_perm") or "").strip()

        # --------------------------------------------------------
        # 2. Récupération et vérification des métadonnées
        # --------------------------------------------------------

        uuid_suivi = str(metadata.get("uuid_suivi") or "").strip()
        groupe_suivi = str(metadata.get("groupe_suivi") or "").strip().lower()
        codesitep = str(metadata.get("codesitep") or "").strip()
        nom_complet = str(metadata.get("nom_complet") or "").strip()

        try:
            cd_nom = int(metadata.get("cd_nom"))
            id_obs = int(metadata.get("id_obs"))
            taille_maille_metadata = int(metadata.get("taille_maille"))
        except (TypeError, ValueError):
            QMessageBox.critical(
                self,
                "Métadonnées invalides",
                "cd_nom, id_obs ou taille_maille est invalide dans metadata_suivi."
            )
            return

        erreurs_metadata = []

        if not uuid_suivi:
            erreurs_metadata.append("uuid_suivi est absent.")

        if groupe_suivi not in ("faune", "flore"):
            erreurs_metadata.append(
                "groupe_suivi doit valoir 'faune' ou 'flore'."
            )

        if not codesitep:
            erreurs_metadata.append("codesitep est absent.")

        if not nom_complet:
            erreurs_metadata.append("nom_complet est absent.")

        if taille_maille_metadata <= 0:
            erreurs_metadata.append("taille_maille doit être positive.")

        if not id_perm_suivi:
            erreurs_metadata.append(
                "id_perm du suivi est absent de metadata_suivi."
            )

        if erreurs_metadata:
            QMessageBox.critical(
                self,
                "Métadonnées invalides",
                "\n".join(erreurs_metadata)
            )
            return

        nb_mailles = len(self.donnees_mailles_import)

        # --------------------------------------------------------
        # 3. Confirmation utilisateur
        # --------------------------------------------------------

        reponse = QMessageBox.question(
            self,
            "Confirmer le transfert",
            (
                f"{nb_mailles} maille(s) renseignée(s) détectée(s) dans "
                "le GeoPackage.\n\n"
                f"UUID suivi : {uuid_suivi}\n"
                f"Site : {codesitep}\n"
                f"Espèce : {nom_complet} ({cd_nom})\n"
                f"Observateur : {metadata.get('observateur') or id_obs}\n\n"
                "Les mailles déjà transférées lors d'un précédent import "
                "seront mises à jour.\n\n"
                "Voulez-vous continuer ?"
            ),
            QMSG_YES | QMSG_NO,
            QMSG_NO
        )

        if reponse != QMSG_YES:
            self._log_import("Transfert annulé par l'utilisateur.")
            return

        # --------------------------------------------------------
        # 4. Préparation de la connexion
        # --------------------------------------------------------

        pg_conn = None
        pg_cur = None

        progress = QProgressDialog(
            "Transfert des observations dans PostgreSQL...",
            None,
            0,
            0,
            self
        )
        progress.setWindowTitle("Transfert en cours")
        progress.setWindowModality(QT_WINDOW_MODAL)
        progress.setCancelButton(None)
        progress.setMinimumDuration(0)
        progress.show()

        QApplication.setOverrideCursor(QT_WAIT_CURSOR)
        QApplication.processEvents()

        try:
            if self.pg_service_path and os.path.exists(self.pg_service_path):
                os.environ["PGSERVICEFILE"] = self.pg_service_path

            pg_conn = psycopg2.connect(
                service="bd CEN (admin)",
                connect_timeout=10,
                application_name="plugin_suivi_import_observations",
                options="-c statement_timeout=30000 -c lock_timeout=5000"
            )

            pg_cur = pg_conn.cursor()

            # --------------------------------------------------------
            # 5. Vérification du suivi dans PostgreSQL
            # --------------------------------------------------------

            pg_cur.execute("""
                SELECT
                    uuid_suivi,
                    id_perm,
                    codesitep,
                    groupe_suivi,
                    cd_nom,
                    taille_maille,
                    id_obs,
                    statut_suivi
                FROM suivi_cen.suivi_espece
                WHERE uuid_suivi = %s;
            """, (
                uuid_suivi,
            ))

            suivi_bdd = pg_cur.fetchone()

            if not suivi_bdd:
                raise Exception(
                    "Le suivi indiqué dans le GeoPackage n'existe pas "
                    "dans suivi_cen.suivi_espece."
                )

            (
                uuid_suivi_bdd,
                id_perm_suivi_bdd,
                codesitep_bdd,
                groupe_suivi_bdd,
                cd_nom_bdd,
                taille_maille_bdd,
                id_obs_bdd,
                statut_suivi_bdd
            ) = suivi_bdd

            # --------------------------------------------------------
            # 6. Comparaison des métadonnées avec le suivi central
            # --------------------------------------------------------

            differences = []

            if str(id_perm_suivi_bdd or "").strip() != id_perm_suivi:
                differences.append(
                    f"id_perm : GeoPackage={id_perm_suivi}, "
                    f"base={id_perm_suivi_bdd}"
                )
            if str(codesitep_bdd) != codesitep:
                differences.append(
                    f"codesitep : GeoPackage={codesitep}, "
                    f"base={codesitep_bdd}"
                )

            if str(groupe_suivi_bdd).strip().lower() != groupe_suivi:
                differences.append(
                    f"groupe_suivi : GeoPackage={groupe_suivi}, "
                    f"base={groupe_suivi_bdd}"
                )

            if int(cd_nom_bdd) != cd_nom:
                differences.append(
                    f"cd_nom : GeoPackage={cd_nom}, base={cd_nom_bdd}"
                )

            if int(taille_maille_bdd) != taille_maille_metadata:
                differences.append(
                    f"taille_maille : GeoPackage={taille_maille_metadata}, "
                    f"base={taille_maille_bdd}"
                )

            if int(id_obs_bdd) != id_obs:
                differences.append(
                    f"id_obs : GeoPackage={id_obs}, base={id_obs_bdd}"
                )

            if differences:
                raise Exception(
                    "Les métadonnées du GeoPackage ne correspondent pas "
                    "au suivi enregistré dans PostgreSQL :\n\n- "
                    + "\n- ".join(differences)
                )

            # --------------------------------------------------------
            # 7. Vérification des observations déjà importées
            # --------------------------------------------------------

            ids_mailles = [
                int(maille["id_maille"])
                for maille in self.donnees_mailles_import
            ]

            pg_cur.execute("""
                SELECT
                    id_maille,
                    code_maille,
                    uuid_resultat
                FROM suivi_cen.observation_maille
                WHERE uuid_suivi = %s
                AND id_maille = ANY(%s);
            """, (
                uuid_suivi,
                ids_mailles
            ))

            observations_existantes = pg_cur.fetchall()

            ids_mailles_deja_importees = {
                row[0] for row in observations_existantes
            }

            if ids_mailles_deja_importees:
                self._log_import(
                    f"{len(ids_mailles_deja_importees)} maille(s) déjà "
                    "transférée(s) lors d'un précédent import : elles "
                    "seront mises à jour plutôt que dupliquées."
                )

            # --------------------------------------------------------
            # 8. Préparation des observations
            # --------------------------------------------------------

            source_gpkg = os.path.basename(chemin_gpkg)
            observations_a_inserer = []
            observations_a_mettre_a_jour = []

            for maille in self.donnees_mailles_import:
                uuid_resultat = str(
                    maille["uuid_resultat"]
                ).strip()

                # Identifiant permanent provisoire, sans id_perm du suivi
                id_perm_observation = self._generer_id_perm_observation(
                    id_perm_suivi=id_perm_suivi,
                    id_maille=maille["id_maille"],
                    uuid_resultat=uuid_resultat
                )


                try:
                    id_maille = int(maille["id_maille"])
                    taille_maille = int(maille["taille_maille"])
                    presence_absence = int(
                        maille["presence_absence"]
                    )
                except (TypeError, ValueError):
                    raise Exception(
                        f"Valeur numérique invalide pour la maille "
                        f"{maille.get('code_maille')}."
                    )

                if taille_maille != taille_maille_metadata:
                    raise Exception(
                        f"La taille de la maille {maille['code_maille']} "
                        f"est de {taille_maille} m, alors que le suivi "
                        f"utilise {taille_maille_metadata} m."
                    )

                if presence_absence not in (0, 1):
                    raise Exception(
                        f"Valeur presence_absence invalide pour la maille "
                        f"{maille['code_maille']}."
                    )

                texte_date_obs = str(
                    maille["date_obs"] or ""
                ).strip()

                try:
                    date_obs = datetime.strptime(
                        texte_date_obs,
                        "%Y-%m-%d"
                    ).date()
                except ValueError:
                    raise Exception(
                        f"Date invalide pour la maille "
                        f"{maille['code_maille']} : {texte_date_obs}.\n"
                        "Le format attendu est AAAA-MM-JJ."
                    )

                code_maille = str(maille["code_maille"]).strip()

                if id_maille in ids_mailles_deja_importees:
                    # Maille déjà transférée : on met à jour la date
                    # et la présence/absence plutôt que de dupliquer.
                    observations_a_mettre_a_jour.append((
                        date_obs,
                        presence_absence,
                        source_gpkg,
                        uuid_suivi,
                        id_maille,
                    ))
                else:
                    observations_a_inserer.append((
                        id_perm_observation,
                        uuid_suivi,
                        groupe_suivi,
                        codesitep,
                        cd_nom,
                        nom_complet,
                        id_obs,
                        id_maille,
                        code_maille,
                        taille_maille,
                        date_obs,
                        presence_absence,
                        uuid_resultat,
                        source_gpkg
                    ))

            # --------------------------------------------------------
            # 9. Insertion des nouvelles observations
            # --------------------------------------------------------

            if observations_a_inserer:
                pg_cur.executemany("""
                    INSERT INTO suivi_cen.observation_maille (
                        id_perm,
                        uuid_suivi,
                        groupe_suivi,
                        codesitep,
                        cd_nom,
                        nom_complet,
                        id_obs,
                        id_maille,
                        code_maille,
                        taille_maille,
                        date_obs,
                        presence_absence,
                        uuid_resultat,
                        source_gpkg
                    )
                    VALUES (
                        %s, %s, %s, %s, %s, %s, %s,
                        %s, %s, %s, %s, %s, %s, %s
                    );
                """, observations_a_inserer)

            # --------------------------------------------------------
            # 9bis. Mise à jour des observations déjà existantes
            # --------------------------------------------------------

            if observations_a_mettre_a_jour:
                ids_maj = [
                    ligne[4]  # id_maille
                    for ligne in observations_a_mettre_a_jour
                ]

                pg_cur.execute("""
                    SELECT
                        id_maille,
                        code_maille,
                        date_obs,
                        presence_absence
                    FROM suivi_cen.observation_maille
                    WHERE uuid_suivi = %s
                    AND id_maille = ANY(%s);
                """, (
                    uuid_suivi,
                    ids_maj
                ))

                anciennes_valeurs = {
                    row[0]: {
                        "code_maille": row[1],
                        "date_obs": row[2],
                        "presence_absence": row[3],
                    }
                    for row in pg_cur.fetchall()
                }

                lignes_journal = []
                for (
                    nouvelle_date,
                    nouvelle_presence,
                    _source_gpkg,
                    _uuid_suivi,
                    id_maille_maj
                ) in observations_a_mettre_a_jour:
                    ancien = anciennes_valeurs.get(id_maille_maj, {})
                    lignes_journal.append(
                        f"- Maille {ancien.get('code_maille', '?')} "
                        f"(id_maille {id_maille_maj}) : "
                        f"date {ancien.get('date_obs')} -> {nouvelle_date}, "
                        f"présence/absence "
                        f"{ancien.get('presence_absence')} -> "
                        f"{nouvelle_presence}"
                    )

                self._log_import(
                    f"{len(observations_a_mettre_a_jour)} observation(s) "
                    "existante(s) mise(s) à jour (ancienne valeur -> "
                    "nouvelle valeur) :\n"
                    + "\n".join(lignes_journal)
                )

                pg_cur.executemany("""
                    UPDATE suivi_cen.observation_maille
                    SET date_obs = %s,
                        presence_absence = %s,
                        source_gpkg = %s
                    WHERE uuid_suivi = %s
                    AND id_maille = %s;
                """, observations_a_mettre_a_jour)

            # --------------------------------------------------------
            # 10. Mise à jour du suivi
            # --------------------------------------------------------

            pg_cur.execute("""
                UPDATE suivi_cen.suivi_espece
                SET statut_suivi = 'importe',
                    date_import = now()
                WHERE uuid_suivi = %s;
            """, (
                uuid_suivi,
            ))

            pg_conn.commit()

            # --------------------------------------------------------
            # 11. Mise à jour de l'interface
            # --------------------------------------------------------

            self.controle_import_valide = False
            self.btn_transferer_resultats.setEnabled(False)

            self._log_import(
                "Transfert terminé avec succès.\n"
                f"- UUID suivi : {uuid_suivi}\n"
                f"- Nouvelles observations insérées : "
                f"{len(observations_a_inserer)}\n"
                f"- Observations mises à jour : "
                f"{len(observations_a_mettre_a_jour)}\n"
                f"- Fichier source : {source_gpkg}\n"
                "- Statut du suivi : importe"
            )

            QMessageBox.information(
                self,
                "Transfert terminé",
                (
                    "Les observations ont été transférées avec succès.\n\n"
                    f"Nouvelles observations insérées : "
                    f"{len(observations_a_inserer)}\n"
                    f"Observations mises à jour : "
                    f"{len(observations_a_mettre_a_jour)}\n"
                    f"UUID suivi : {uuid_suivi}"
                )
            )

        except Exception as e:
            if pg_conn is not None:
                pg_conn.rollback()

            self._log_import(
                f"Échec du transfert : {e}"
            )

            QMessageBox.critical(
                self,
                "Erreur de transfert",
                f"Le transfert dans PostgreSQL a échoué :\n\n{e}"
            )

        finally:
            if pg_cur is not None:
                pg_cur.close()

            if pg_conn is not None:
                pg_conn.close()

            QApplication.restoreOverrideCursor()
            progress.close()
            QApplication.processEvents()


