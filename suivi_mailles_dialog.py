    def _recuperer_code_site_mere(self, pg_cur, codesitep):
        """
        Récupère le code_site_mere associé au site sélectionné.
        Si le code sélectionné est déjà un code_site_mere, il est aussi accepté.
        """

        pg_cur.execute("""
            SELECT sc.code_site_mere
            FROM bd_site_cen.site_cen sc
            WHERE sc.codesitep = %s
            OR sc.code_site_mere = %s
            LIMIT 1;
        """, (
            codesitep,
            codesitep
        ))

        row = pg_cur.fetchone()

        if not row:
            return None

        return row[0]

    def _recuperer_codesiteps_du_site_mere(self, pg_cur, code_site_mere):
        """
        Récupère tous les codesitep (sous-sites) rattachés à un code_site_mere,
        en ne gardant que ceux qui ont une géométrie exploitable dans
        bd_site_cen.geo_site — exactement la même jointure que celle utilisée
        par mailles_cen.create_maillage() pour calculer les mailles (voir sa
        CTE "sites"). Un site sans géométrie dans geo_site (ex. une ligne
        "étiquette" qui se référence elle-même comme site mère, sans
        géométrie propre) n'est jamais traité par create_maillage : il ne
        doit donc jamais être exigé dans la liste des sous-sites à mailler,
        sinon _recuperer_ou_generer_mailles_site échoue systématiquement.

        Pour un site simple, la liste ne contient qu'un seul élément
        (le site est son propre site mère et possède sa propre géométrie).
        """
        pg_cur.execute("""
            SELECT sc.codesitep
            FROM bd_site_cen.site_cen sc
            JOIN bd_site_cen.geo_site gs
                ON gs.codesitep = sc.codesitep
            WHERE sc.code_site_mere = %s
            AND gs.geom IS NOT NULL
            ORDER BY sc.codesitep;
        """, (code_site_mere,))

        return [row[0] for row in pg_cur.fetchall()]


    def _recuperer_mailles_sites(self, pg_cur, codesiteps, taille_maille):
                """
                Récupère les mailles existantes pour UNE LISTE de codesitep
                (un ou plusieurs sous-sites d'un même site mère) et une taille donnée.
                Chaque maille conserve son codesitep d'origine.
                """
                if not codesiteps:
                    return []
    
                pg_cur.execute("""
                    SELECT
                        sm.id_maille,
                        sm.codesitep,
                        sm.code_maille,
                        sm.taille_maille,
                        ST_SRID(ms.geom) AS srid,
                        ST_AsBinary(ST_Multi(ms.geom)) AS geom_wkb
                    FROM mailles_cen.site_maille sm
                    JOIN mailles_cen.maille_sitescen ms
                        ON ms.id = sm.id_maille
                    WHERE sm.codesitep = ANY(%s)
                    AND sm.taille_maille = %s
                    ORDER BY sm.codesitep, sm.code_maille;
                """, (
                    list(codesiteps),
                    int(taille_maille)
                ))
    
                return pg_cur.fetchall()

    def _generer_mailles_site_sql(self, pg_cur, code_site_mere, taille_maille):
        """
        Appelle la fonction SQL mailles_cen.create_maillage
        .
        """

        pg_cur.execute("""
            SELECT
                nb_mailles_calculees,
                nb_mailles_inserees,
                nb_liens_site_maille_crees
            FROM mailles_cen.create_maillage(%s, %s);
        """, (
            code_site_mere,
            int(taille_maille)
        ))

        return pg_cur.fetchone()

    def _recuperer_ou_generer_mailles_site(
        self,
        pg_conn,
        pg_cur,
        codesiteps,
        code_site_mere,
        taille_maille
    ):
        """
        Récupère les mailles existantes pour TOUS les codesitep listés
        (un site mère peut en contenir plusieurs, un site simple un seul).

        Si des mailles manquent pour un ou plusieurs sous-sites, propose à
        l'utilisateur de les générer avec la fonction SQL
        mailles_cen.create_maillage, qui travaille au niveau du site mère
        et complète uniquement les sous-sites manquants (ON CONFLICT DO
        NOTHING côté SQL).

        Après génération, on relit les mailles avec une nouvelle connexion
        PostgreSQL. Cela reproduit le comportement du deuxième clic sur
        "Créer suivi".
        """

        def chercher_mailles_avec_curseur(cur):
            """
            Recherche les mailles pour l'ensemble des codesitep du site
            mère (ou l'unique codesitep pour un site simple).
            """

            return self._recuperer_mailles_sites(
                pg_cur=cur,
                codesiteps=codesiteps,
                taille_maille=taille_maille
            )

        def codesiteps_manquants_dans(mailles_trouvees):
            codesiteps_presents = {m[1] for m in mailles_trouvees}
            return sorted(set(codesiteps) - codesiteps_presents)

        # ------------------------------------------------------------
        # 1. Recherche initiale avec la connexion actuelle
        # ------------------------------------------------------------

        mailles = chercher_mailles_avec_curseur(pg_cur)
        manquants = codesiteps_manquants_dans(mailles)

        if mailles and not manquants:
            return mailles

        # ------------------------------------------------------------
        # 2. Demande à l'utilisateur pour générer les mailles manquantes
        # ------------------------------------------------------------

        sous_sites_manquants = manquants if mailles else list(codesiteps)

        reponse = QMessageBox.question(
            self,
            "Mailles inexistantes",
            (
                f"Mailles de {taille_maille} m manquantes pour {len(sous_sites_manquants)} "
                f"sous-site(s) du site mère {code_site_mere} :\n\n"
                f"{', '.join(sous_sites_manquants)}\n\n"
                "Voulez-vous générer les mailles manquantes ?"
            ),
            QMSG_YES | QMSG_NO,
            QMSG_YES
        )

        if reponse != QMSG_YES:
            return []

        # ------------------------------------------------------------
        # 3. Génération SQL des mailles
        # ------------------------------------------------------------

        try:
            resultat_generation = self._generer_mailles_site_sql(
                pg_cur=pg_cur,
                code_site_mere=code_site_mere,
                taille_maille=taille_maille
            )

            pg_conn.commit()

        except Exception as e:
            pg_conn.rollback()
            raise Exception(
                "La génération des mailles a échoué.\n\n"
                f"Détail : {e}"
            )

        # ------------------------------------------------------------
        # 4. Résumé de génération
        # ------------------------------------------------------------

        if resultat_generation:
            nb_calculees = resultat_generation[0]
            nb_inserees = resultat_generation[1]
            nb_liens = resultat_generation[2]

            self._log(
                f"Génération des mailles terminée :\n"
                f"- Mailles calculées : {nb_calculees}\n"
                f"- Mailles insérées : {nb_inserees}\n"
                f"- Liens site/maille créés : {nb_liens}",
                onglet="preparation"
            )
            

    # ------------------------------------------------------------
    # 5. Relecture avec une nouvelle connexion PostgreSQL
    #    Version sécurisée avec timeouts
    # ------------------------------------------------------------

        pg_conn_relecture = None
        pg_cur_relecture = None
        derniere_erreur_relecture = None

        try:
            if self.pg_service_path and os.path.exists(self.pg_service_path):
                os.environ["PGSERVICEFILE"] = self.pg_service_path

            self._log(
                "Relecture des mailles avec une nouvelle connexion PostgreSQL...",
                onglet="preparation"
            )

            # Connexion limitée à 5 secondes
            # statement_timeout : une requête ne peut pas durer plus de 15 secondes
            # lock_timeout : attente de verrou limitée à 5 secondes
            pg_conn_relecture = psycopg2.connect(
                service="bd CEN (admin)",
                connect_timeout=5,
                application_name="plugin_suivi_relecture_mailles",
                options="-c statement_timeout=15000 -c lock_timeout=5000"
            )

            pg_conn_relecture.autocommit = True
            pg_cur_relecture = pg_conn_relecture.cursor()

            debut_relecture = time.perf_counter()

            mailles = chercher_mailles_avec_curseur(pg_cur_relecture)
            manquants = codesiteps_manquants_dans(mailles)

            duree_relecture = round(time.perf_counter() - debut_relecture, 2)

            if mailles and not manquants:
                self._log(
                    f"Mailles retrouvées après génération avec nouvelle connexion : "
                    f"{len(mailles)} maille(s), durée {duree_relecture} seconde(s).",
                    onglet="preparation"
                )
                return mailles

            self._log(
                f"Relecture terminée mais des sous-sites restent sans mailles "
                f"({', '.join(manquants) if manquants else 'tous'}), "
                f"durée {duree_relecture} seconde(s).",
                onglet="preparation"
            )

        except Exception as e:
            derniere_erreur_relecture = e
            self._log(
                f"Erreur pendant la relecture avec nouvelle connexion : {e}",
                onglet="preparation"
            )

        finally:
            if pg_cur_relecture:
                pg_cur_relecture.close()

            if pg_conn_relecture:
                pg_conn_relecture.close()


        # ------------------------------------------------------------
        # 6. Erreur finale si aucune maille retrouvée
        # ------------------------------------------------------------

        message_erreur = (
            "La fonction SQL de génération a été exécutée, "
            "mais certains sous-sites restent sans maille.\n\n"
            f"Sous-sites demandés : {', '.join(codesiteps)}\n"
            f"Code site mère utilisé : {code_site_mere}\n"
            f"Taille maille : {taille_maille}\n\n"
            "Même après relecture avec une nouvelle connexion PostgreSQL, "
            "certains sous-sites n'ont pas de mailles."
        )

        if derniere_erreur_relecture:
            message_erreur += (
                "\n\nDernière erreur de relecture :\n"
                f"{derniere_erreur_relecture}"
            )

        raise Exception(message_erreur)


    
