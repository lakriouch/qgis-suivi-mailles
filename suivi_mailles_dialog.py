    def _initialiser_onglet_journal(self):
        """
        Initialise l'onglet Journal : point de convergence de tous les
        messages de log du plugin (préparation, terrain, import).
        """
        self._journal_entries = []  # historique en mémoire, utile si besoin d'exporter plus tard
        self.btn_effacer_journal.clicked.connect(
            self._effacer_journal
        )

    def _log(self, message, onglet="general"):
        """
        Point d'entrée unique pour journaliser un message, quel que soit
        l'onglet d'origine.
        """
        horodatage = datetime.now().strftime("%H:%M:%S")
        etiquettes = {"preparation": "Préparation", "terrain": "Terrain", "import": "Import"}
        prefixe = etiquettes.get(onglet, onglet.capitalize())

        ligne = f"{horodatage} [{prefixe}] {message}"
        self._journal_entries.append(ligne)

        if hasattr(self, "txt_journal"):
            self.txt_journal.appendPlainText(ligne)


    def _log_terrain(self, message):
        """Signature conservée ; redirige vers le journal centralisé."""
        self._log(message, onglet="terrain")

    def _log_import(self, message):
        """Signature conservée ; redirige vers le journal centralisé."""
        self._log(str(message), onglet="import")


    def _effacer_journal(self):
        """Efface l'affichage et l'historique du journal."""

        self._journal_entries.clear()

        if hasattr(self, "txt_journal"):
            self.txt_journal.clear()
